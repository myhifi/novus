// ═══════════════════════════════════════════════════
// 🖼️  Generate Local Images List
// ═══════════════════════════════════════════════════
// Reads public/products/ at BUILD time and writes a typed
// constant consumed by the admin image picker (Phase 8).
//
// Why build time: Vercel serves public/ from the CDN and
// the serverless runtime cannot read it at request time.

import { readdirSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";

const PRODUCTS_DIR = join(process.cwd(), "public", "products");
const OUT_FILE = join(
  process.cwd(),
  "src",
  "lib",
  "constants",
  "local-images.generated.ts"
);

const ALLOWED_EXTENSIONS = new Set([
  ".jpg",
  ".jpeg",
  ".png",
  ".webp",
  ".avif",
  ".gif",
  ".svg",
]);

function ensureDir(dir: string) {
  if (!existsSync(dir)) {
    mkdirSync(dir, { recursive: true });
  }
}

function main() {
  // Both directories must exist before we read/write.
  ensureDir(PRODUCTS_DIR);
  ensureDir(dirname(OUT_FILE));

  const files = readdirSync(PRODUCTS_DIR)
    .filter((name) => {
      const dot = name.lastIndexOf(".");
      if (dot === -1) return false;
      return ALLOWED_EXTENSIONS.has(name.slice(dot).toLowerCase());
    })
    .sort();

  const lines = files.map((n) => `  "/products/${n}",`).join("\n");

  const content = `// ═══════════════════════════════════════════════════
// 🖼️  Local Images (AUTO-GENERATED — do not edit manually)
// ═══════════════════════════════════════════════════
// Generated by scripts/generate-local-images.ts
// Runs automatically before \`npm run dev\` and \`npm run build\`.
//
// To add new images: drop them in public/products/ and restart dev.

export const LOCAL_IMAGES = [
${lines}
] as const;

export type LocalImage = (typeof LOCAL_IMAGES)[number];
`;

  writeFileSync(OUT_FILE, content, "utf8");
  console.log(
    `✅ Generated ${files.length} product image reference(s) → src/lib/constants/local-images.generated.ts`
  );
}

main();
